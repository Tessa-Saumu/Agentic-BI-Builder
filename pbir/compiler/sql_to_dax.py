"""
SQL -> DAX translation.

Extracted from builder.py's original "SQL -> DAX translation" section
(the module docstring's own sectioning). Translates a KPISpec's
sql_query into a basic DAX measure expression (pbir_reference.md
Section 2.12).

Supported DAX per the Measure model docstring: SUM, AVERAGE, COUNT,
DIVIDE, IF. This module recognizes several concrete SQL shapes built
from those primitives -- the KPI SQL is always a single SELECT
(enforced by KPISpec's own field_validator), generated by the LLM
Domain/KPI node against one of the known datasets:

  1. Plain single aggregate:      SUM(col) / AVG(col) / COUNT(col)
  2. COUNT(*):                    maps to DAX COUNTROWS('table')
  3. ROUND(<agg-expr>, n):        precision wrapper around any of the
                                   above, including the ratio and
                                   conditional-percentage shapes below
                                   -- maps to DAX ROUND(<translated-
                                   expr>, n)
  4. Ratio of two aggregates:     SUM(a)/COUNT(b) -> DAX
                                   DIVIDE(SUM(a), COUNT(b))
  5. Conditional-count percentage: SUM(CASE WHEN col = 'val' THEN 1.0
                                   ELSE 0.0 END) * 100.0 / COUNT(*) --
                                   the standard "% of rows matching a
                                   condition" SQL idiom (SQL's CASE
                                   WHEN is the IF the Measure
                                   docstring lists as in-scope) -> DAX
                                   DIVIDE(COUNTROWS(FILTER('table',
                                   'table'[col] = "val")),
                                   COUNTROWS('table')) * 100

Anything outside these shapes (nested aggregations the module doesn't
recognize, window functions, multiple independently-selected
aggregate columns that aren't a ratio, etc.) is NOT guessed at --
raised as SQLToDaxError so the builder can record it in state.errors
and skip that KPI, rather than emitting DAX that's silently wrong.

Public names (translate, translate_multi, extract_group_by_column,
SQLToDaxError) are exercised directly by their own unit test suites in
tests/test_pbir_compiler.py, in addition to being used internally by
builder.run_pbir_compiler. builder.py re-exports all of them so
`from pbir.compiler.builder import translate` (etc.) continues to work
unchanged for any existing caller/test.
"""
from __future__ import annotations

import re
from dataclasses import dataclass


class SQLToDaxError(Exception):
    """Raised when a KPI's SQL can't be confidently mapped to basic DAX."""


@dataclass(frozen=True)
class DaxTranslation:
    expression: str
    aggregation: str  # SUM | AVERAGE | COUNT | DIVIDE | COUNTROWS | ROUND
    source_column: str  # the raw column name being aggregated (for dtype/format lookups)
    is_currency: bool = False
    is_percentage: bool = False


# SQL aggregate function -> DAX function name
_AGG_MAP = {
    "sum": "SUM",
    "avg": "AVERAGE",
    "count": "COUNT",
}

# SCOPE EXTENSION (2026-07-12): to satisfy the "all three datasets open
# successfully" acceptance criterion, online_retail's KPIs require two new
# shapes the original basic-DAX set (SUM/AVERAGE/COUNT/DIVIDE/IF) didn't
# cover -- both are standard, well-documented DAX, not exotic scope:
#
#   1. Row-wise arithmetic inside an aggregate: SUM(ColA * ColB) -- e.g.
#      online_retail's revenue = SUM(Quantity * UnitPrice), since there is
#      no precomputed "revenue" column. DAX has no way to SUM a per-row
#      expression directly the way SQL's SUM(a*b) does; the standard DAX
#      equivalent is the row-context iterator SUMX(table, expr). Likewise
#      AVERAGE(a*b) -> AVERAGEX(table, expr), added for consistency with
#      SUMX even though no current KPI in any of the 3 datasets uses it --
#      it's the same shape of extension and costs nothing to support
#      alongside SUMX.
#   2. COUNT(DISTINCT col) -> DAX DISTINCTCOUNT(col). Needed for
#      online_retail's Average Order Value KPI (COUNT(DISTINCT InvoiceNo),
#      counting unique orders rather than line-item rows).
#
# A third shape -- a SQL WHERE clause -- is handled separately, see the
# _WHERE_CLAUSE_RE section below and translate()'s WHERE-stripping step.
_ROWWISE_AGG_MAP = {
    "sum": "SUMX",
    "avg": "AVERAGEX",
}

# SUM(ColA * ColB) or AVG(ColA * ColB) -- exactly two column operands
# multiplied together inside the aggregate. Only a bare "col * col" product
# is recognized (matching every real KPI seen so far); other arithmetic
# (+, -, /, more than 2 operands, a literal constant operand) is NOT
# guessed at and falls through to the existing "unsupported shape" error.
_ROWWISE_PRODUCT_RE = re.compile(
    r"""^(?P<agg>SUM|AVG)\s*\(\s*
        (?P<col1>[A-Za-z_][A-Za-z0-9_]*)\s*\*\s*(?P<col2>[A-Za-z_][A-Za-z0-9_]*)
        \s*\)$""",
    re.IGNORECASE | re.VERBOSE,
)

# COUNT(DISTINCT col) -- as its own aggregate, standalone or as one operand
# of a ratio (e.g. SUM(a*b) / COUNT(DISTINCT c)).
_DISTINCT_COUNT_RE = re.compile(
    r"""^COUNT\s*\(\s*DISTINCT\s+(?P<col>[A-Za-z_][A-Za-z0-9_]*)\s*\)$""",
    re.IGNORECASE,
)

# A SQL WHERE clause on the outermost query -- captured and stripped before
# the rest of translate() runs, then re-applied as a DAX CALCULATE(...)
# filter argument around the final translated expression. Two forms are
# recognized (matching every WHERE in the 3 datasets' real KPIs:
# "Quantity > 0", "CustomerID IS NOT NULL", "1=1" treated as no-op):
# a single "<column> <op> <value>" comparison, or a single
# "<column> IS [NOT] NULL" null check; AND/OR-joined multi-condition
# WHEREs are NOT guessed at and fall through to the existing "unsupported
# shape" error.
_WHERE_CLAUSE_RE = re.compile(
    r"""\s+WHERE\s+(?P<condition>[A-Za-z_][A-Za-z0-9_]*\s*(?:>|<|>=|<=|=|!=|<>)\s*'?[^'\s]+'?|[A-Za-z_][A-Za-z0-9_]*\s+IS\s+(?:NOT\s+)?NULL|1\s*=\s*1)
        \s*(?P<trailing>GROUP\s+BY.*|ORDER\s+BY.*|LIMIT.*)?$""",
    re.IGNORECASE | re.VERBOSE | re.DOTALL,
)

_CONDITION_RE = re.compile(
    r"""^(?P<col>[A-Za-z_][A-Za-z0-9_]*)\s*(?:(?P<op>>=|<=|!=|<>|>|<|=)\s*'?(?P<val>[^'\s]+)'?|IS\s+(?P<null_not>NOT\s+)?NULL)$""",
    re.IGNORECASE | re.VERBOSE,
)

# SQL comparison operator -> DAX comparison operator (identical for every
# operator actually seen in these datasets; kept as an explicit map rather
# than assuming SQL and DAX operators always coincide for every future one).
_SQL_TO_DAX_OP = {
    ">": ">", "<": "<", ">=": ">=", "<=": "<=", "=": "=", "!=": "<>", "<>": "<>",
}

# COUNT(*) as the sole aggregate: "SELECT COUNT(*) AS n FROM data".
_COUNT_STAR_RE = re.compile(
    r"""^SELECT\s+COUNT\s*\(\s*\*\s*\)\s+AS\s+\w+\s+FROM\s+[A-Za-z_][A-Za-z0-9_]*\s*$""",
    re.IGNORECASE,
)

# A grouped KPI (chart data): one or more plain/expression columns selected
# alongside exactly one aggregate call, with a GROUP BY.
_GROUPED_AGG_RE = re.compile(
    r"""(?P<agg>SUM|AVG|COUNT)\s*\(\s*(?:DISTINCT\s+)?(?P<col>[A-Za-z_][A-Za-z0-9_]*)\s*\)
        \s+AS\s+\w+
    """,
    re.IGNORECASE | re.VERBOSE,
)

# Same as above but for COUNT(*) AS alias inside a grouped query.
_GROUPED_COUNT_STAR_RE = re.compile(r"COUNT\s*\(\s*\*\s*\)\s+AS\s+\w+", re.IGNORECASE)

# A ratio KPI: <aggregate-expr> / <aggregate-expr> AS alias FROM table, no
# GROUP BY. Only used now to detect THAT a top-level "/" exists outside any
# parens (see _split_top_level_operator below) -- the two sides are each
# recursively translated via _translate_core so this composes with every
# other shape (plain aggregate, SUMX/AVERAGEX product, DISTINCTCOUNT), e.g.
# online_retail's AOV: SUM(Quantity * UnitPrice) / COUNT(DISTINCT InvoiceNo).
_RATIO_RE = re.compile(
    r"""^SELECT\s+(?P<expr>.+)\s+AS\s+\w+\s+FROM\s+[A-Za-z_][A-Za-z0-9_]*\s*$""",
    re.IGNORECASE | re.VERBOSE | re.DOTALL,
)

# ROUND(<inner>, <n>) AS alias FROM table -- captures the inner expression
# and precision, leaving the inner expression to be translated recursively.
# Only matches when ROUND wraps the ENTIRE select expression (i.e. ROUND is
# the outermost call), which is the only shape this compiler handles.
_ROUND_WRAPPER_RE = re.compile(
    r"""^SELECT\s+ROUND\s*\(\s*(?P<inner>.+?)\s*,\s*(?P<precision>\d+)\s*\)\s+AS\s+\w+\s+
        FROM\s+(?P<table>[A-Za-z_][A-Za-z0-9_]*)
        (?P<rest>.*)
        $""",
    re.IGNORECASE | re.VERBOSE | re.DOTALL,
)

# The conditional-count-percentage idiom, in either of two SQL phrasings
# that mean the same thing:
#   SUM(CASE WHEN <col> = '<val>' THEN 1.0 ELSE 0.0 END) * 100.0 / COUNT(*)
#   (CAST(COUNT(CASE WHEN <col> = '<val>' THEN 1 END) AS FLOAT) / COUNT(*)) * 100
# COUNT(CASE WHEN ... THEN 1 END) with no ELSE is equivalent to SUM(...THEN
# 1.0 ELSE 0.0 END): COUNT skips the implicit NULL from the no-match
# branch, so it counts exactly the matching rows -- same value, different
# SQL idiom. Both translate to the same DAX FILTER/COUNTROWS idiom below.
_MATCHING_ROW_COUNT_RE = re.compile(
    r"""
    (?:
        SUM\s*\(\s*CASE\s+WHEN\s+(?P<col_a>[A-Za-z_][A-Za-z0-9_]*)\s*=\s*'(?P<val_a>[^']*)'\s*
            THEN\s+1(?:\.0)?\s+ELSE\s+0(?:\.0)?\s+END\s*\)
        |
        COUNT\s*\(\s*CASE\s+WHEN\s+(?P<col_b>[A-Za-z_][A-Za-z0-9_]*)\s*=\s*'(?P<val_b>[^']*)'\s*
            THEN\s+1\s+END\s*\)
    )
    """,
    re.IGNORECASE | re.VERBOSE,
)


def _match_conditional_pct(stripped: str) -> tuple[str, str] | None:
    """
    Returns (col, val) if stripped is the conditional-count-percentage
    idiom in either supported phrasing, else None. See
    _MATCHING_ROW_COUNT_RE above for the two phrasings.
    """
    m = _MATCHING_ROW_COUNT_RE.match(stripped.strip())
    if m:
        rest = stripped.strip()[m.end():].strip()
        if re.fullmatch(r"\*\s*100(?:\.0)?\s*/\s*COUNT\s*\(\s*\*\s*\)", rest, re.IGNORECASE):
            return m.group("col_a") or m.group("col_b"), m.group("val_a") or m.group("val_b")

    cast_prefix = re.match(r"^\(\s*CAST\s*\(\s*", stripped.strip(), re.IGNORECASE)
    if cast_prefix:
        inner = stripped.strip()[cast_prefix.end():]
        m2 = _MATCHING_ROW_COUNT_RE.match(inner)
        if m2:
            rest = inner[m2.end():].strip()
            if re.fullmatch(
                r"AS\s+(?:FLOAT|REAL)\s*\)\s*/\s*COUNT\s*\(\s*\*\s*\)\s*\)\s*\*\s*100(?:\.0)?",
                rest, re.IGNORECASE,
            ):
                return m2.group("col_a") or m2.group("col_b"), m2.group("val_a") or m2.group("val_b")

    return None

# GENERAL CASE WHEN -> DAX IF translation (2026-07-13). SQL's CASE WHEN is
# functionally SQL's IF -- and IF has been on the approved basic-DAX list
# (SUM, AVERAGE, COUNT, DIVIDE, IF) since the very start of this project,
# but until now only ONE narrow CASE WHEN shape was ever recognized (the
# percentage idiom above) -- a bare conditional value, or one nested inside
# SUM/AVG for something other than a 0/1 count-percentage (e.g. "SUM(CASE
# WHEN Total > 50 THEN Total ELSE 0 END)" -- a conditional SUM, not a
# percentage), had no translation path at all. This closes that gap.
#
# Only a single "<column> <op> <value> THEN <then_val> ELSE <else_val> END"
# CASE WHEN is recognized -- both <then_val>/<else_val> may be a bare
# number OR a column reference (needed for "THEN Total ELSE 0", where the
# true-branch is a column, not a literal). Multi-WHEN CASE statements are
# NOT recognized and fall through to the standard unsupported-shape error,
# same as every other not-yet-seen shape in this translator.
_CASE_WHEN_RE = re.compile(
    r"""^CASE\s+WHEN\s+
        (?P<col>[A-Za-z_][A-Za-z0-9_]*)\s*(?P<op>>=|<=|!=|<>|>|<|=)\s*'?(?P<val>[^'\s]+?)'?\s*
        THEN\s+(?P<then_val>[A-Za-z0-9_.]+)\s+ELSE\s+(?P<else_val>[A-Za-z0-9_.]+)\s+END
    $""",
    re.IGNORECASE | re.VERBOSE,
)


def _case_when_to_dax_if(case_expr: str, table_name: str) -> str | None:
    """
    Translates a single CASE WHEN <cond> THEN <a> ELSE <b> END expression
    (as matched by _CASE_WHEN_RE) into DAX's IF(<cond>, <a>, <b>). Returns
    None if case_expr doesn't match the recognized single-condition shape.
    A bare identifier for then_val/else_val is treated as a column
    reference ('table'[col]); anything else (a bare number) is passed
    through as a literal DAX value unchanged.
    """
    m = _CASE_WHEN_RE.match(case_expr.strip())
    if not m:
        return None

    col = m.group("col")
    op = _SQL_TO_DAX_OP.get(m.group("op"))
    if op is None:
        return None
    val = m.group("val")
    try:
        float(val)
        dax_val = val
    except ValueError:
        dax_val = f'"{val}"'

    def _branch(raw: str) -> str:
        try:
            float(raw)
            return raw
        except ValueError:
            return f"'{table_name}'[{raw}]"

    then_branch = _branch(m.group("then_val"))
    else_branch = _branch(m.group("else_val"))

    return f"IF('{table_name}'[{col}] {op} {dax_val}, {then_branch}, {else_branch})"


