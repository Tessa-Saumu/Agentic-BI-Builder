# =====================================================================
# SQL -> DAX translation
#
# Translates a KPISpec's sql_query into a basic DAX measure expression
# (pbir_reference.md §2.12).
#
# Supported DAX per the Measure model docstring: SUM, AVERAGE, COUNT,
# DIVIDE, IF. This module recognizes several concrete SQL shapes built
# from those primitives -- the KPI SQL is always a single SELECT
# (enforced by KPISpec's own field_validator), generated by the LLM
# Domain/KPI node against one of the known datasets:
#
#   1. Plain single aggregate:      SUM(col) / AVG(col) / COUNT(col)
#   2. COUNT(*):                    maps to DAX COUNTROWS('table')
#   3. ROUND(<agg-expr>, n):        precision wrapper around any of the
#                                    above, including the ratio and
#                                    conditional-percentage shapes below
#                                    -- maps to DAX ROUND(<translated-
#                                    expr>, n)
#   4. Ratio of two aggregates:     SUM(a)/COUNT(b) -> DAX
#                                    DIVIDE(SUM(a), COUNT(b))
#   5. Conditional-count percentage: SUM(CASE WHEN col = 'val' THEN 1.0
#                                    ELSE 0.0 END) * 100.0 / COUNT(*) --
#                                    the standard "% of rows matching a
#                                    condition" SQL idiom (SQL's CASE
#                                    WHEN is the IF the Measure
#                                    docstring lists as in-scope) -> DAX
#                                    DIVIDE(COUNTROWS(FILTER('table',
#                                    'table'[col] = "val")),
#                                    COUNTROWS('table')) * 100
#
# Anything outside these shapes (nested aggregations the module doesn't
# recognize, window functions, multiple independently-selected
# aggregate columns that aren't a ratio, etc.) is NOT guessed at --
# raised as SQLToDaxError so the builder can record it in state.errors
# and skip that KPI, rather than emitting DAX that's silently wrong.
# =====================================================================


class SQLToDaxError(Exception):
    """Raised when a KPI's SQL can't be confidently mapped to basic DAX."""


@dataclass(frozen=True)
class DaxTranslation:
    expression: str
    aggregation: str  # SUM | AVERAGE | COUNT | DIVIDE | COUNTROWS | ROUND
    source_column: str  # the raw column name being aggregated (for dtype/format lookups)
    is_currency: bool = False
    is_percentage: bool = False


# SQL aggregate function -> DAX function name
_AGG_MAP = {
    "sum": "SUM",
    "avg": "AVERAGE",
    "count": "COUNT",
}

# A single-value KPI (card): exactly one aggregate call, nothing else
# selected, no GROUP BY. e.g. "SELECT SUM(Total) AS Total FROM data"
_SINGLE_AGG_RE = re.compile(
    r"""^SELECT\s+
        (?P<agg>SUM|AVG|COUNT)\s*\(\s*(?:DISTINCT\s+)?(?P<col>[A-Za-z_][A-Za-z0-9_]*)\s*\)
        \s+AS\s+\w+\s+
        FROM\s+(?P<table>[A-Za-z_][A-Za-z0-9_]*)
        \s*$
    """,
    re.IGNORECASE | re.VERBOSE,
)

# COUNT(*) as the sole aggregate: "SELECT COUNT(*) AS n FROM data".
_COUNT_STAR_RE = re.compile(
    r"""^SELECT\s+COUNT\s*\(\s*\*\s*\)\s+AS\s+\w+\s+FROM\s+[A-Za-z_][A-Za-z0-9_]*\s*$""",
    re.IGNORECASE,
)

# A grouped KPI (chart data): one or more plain/expression columns selected
# alongside exactly one aggregate call, with a GROUP BY.
_GROUPED_AGG_RE = re.compile(
    r"""(?P<agg>SUM|AVG|COUNT)\s*\(\s*(?:DISTINCT\s+)?(?P<col>[A-Za-z_][A-Za-z0-9_]*)\s*\)
        \s+AS\s+\w+
    """,
    re.IGNORECASE | re.VERBOSE,
)

# Same as above but for COUNT(*) AS alias inside a grouped query.
_GROUPED_COUNT_STAR_RE = re.compile(r"COUNT\s*\(\s*\*\s*\)\s+AS\s+\w+", re.IGNORECASE)

# A ratio KPI: SUM(a)/COUNT(b) AS alias FROM table, no GROUP BY.
_RATIO_RE = re.compile(
    r"""^SELECT\s+
        (?P<agg1>SUM|AVG|COUNT)\s*\(\s*(?:DISTINCT\s+)?(?P<col1>[A-Za-z_][A-Za-z0-9_]*)\s*\)
        \s*/\s*
        (?P<agg2>SUM|AVG|COUNT)\s*\(\s*(?:DISTINCT\s+)?(?P<col2>[A-Za-z_][A-Za-z0-9_]*)\s*\)
        \s+AS\s+\w+\s+
        FROM\s+[A-Za-z_][A-Za-z0-9_]*
        \s*$
    """,
    re.IGNORECASE | re.VERBOSE,
)

# ROUND(<inner>, <n>) AS alias FROM table -- captures the inner expression
# and precision, leaving the inner expression to be translated recursively.
# Only matches when ROUND wraps the ENTIRE select expression (i.e. ROUND is
# the outermost call), which is the only shape this compiler handles.
_ROUND_WRAPPER_RE = re.compile(
    r"""^SELECT\s+ROUND\s*\(\s*(?P<inner>.+?)\s*,\s*(?P<precision>\d+)\s*\)\s+AS\s+\w+\s+
        FROM\s+(?P<table>[A-Za-z_][A-Za-z0-9_]*)
        (?P<rest>.*)
        $""",
    re.IGNORECASE | re.VERBOSE | re.DOTALL,
)

# The conditional-count-percentage idiom:
#   SUM(CASE WHEN <col> = '<val>' THEN 1.0 ELSE 0.0 END) * 100.0 / COUNT(*)
# This is the standard SQL "% of rows matching a condition" pattern. SQL's
# CASE WHEN is functionally SQL's IF -- and IF is explicitly in the Measure
# docstring's basic-DAX list -- so this is still within scope, translated to
# DAX's FILTER/COUNTROWS idiom (DAX doesn't have inline CASE WHEN in this
# position the way SQL does; FILTER+COUNTROWS is the standard equivalent).
_CONDITIONAL_PCT_RE = re.compile(
    r"""^\s*SUM\s*\(\s*CASE\s+WHEN\s+
        (?P<col>[A-Za-z_][A-Za-z0-9_]*)\s*=\s*'(?P<val>[^']*)'\s*
        THEN\s+1(?:\.0)?\s+ELSE\s+0(?:\.0)?\s+END\s*\)
        \s*\*\s*100(?:\.0)?\s*/\s*COUNT\s*\(\s*\*\s*\)
    """,
    re.IGNORECASE | re.VERBOSE,
)

# Heuristic: column names commonly representing money, used to attach the
# PBI_FormatHint currency template (§2.12) and a currency formatString.
_CURRENCY_COLUMN_HINTS = {"total", "price", "cost", "revenue", "amount", "sales", "income"}


def _translate_core(stripped: str, table_name: str) -> DaxTranslation:
    """
    Translates a SELECT expression's core aggregate shape (no ROUND
    wrapper, no GROUP BY concerns -- those are handled by the callers).
    Tries, in order: conditional-count-percentage, ratio, COUNT(*),
    plain single aggregate.
    """
    cond_match = _CONDITIONAL_PCT_RE.match(stripped)
    if cond_match:
        col = cond_match.group("col")
        val = cond_match.group("val")
        expression = (
            f"DIVIDE(COUNTROWS(FILTER('{table_name}', '{table_name}'[{col}] = \"{val}\")), "
            f"COUNTROWS('{table_name}')) * 100"
        )
        return DaxTranslation(
            expression=expression,
            aggregation="DIVIDE",
            source_column=col,
            is_percentage=True,
        )

    # _RATIO_RE expects a full "SELECT ... AS alias FROM table" shape, but
    # this function receives a bare inner expression (e.g. when called from
    # inside a ROUND(...) unwrap) -- wrap it to reuse the same regex rather
    # than duplicate the ratio pattern in a second, expression-only form.
    ratio_match = _RATIO_RE.match(f"SELECT {stripped} AS x FROM {table_name}")
    if ratio_match:
        return _ratio_from_match(ratio_match, table_name)

    count_star_match = re.match(r"^COUNT\s*\(\s*\*\s*\)$", stripped, re.IGNORECASE)
    if count_star_match:
        return DaxTranslation(
            expression=f"COUNTROWS('{table_name}')",
            aggregation="COUNTROWS",
            source_column="*",
        )

    single_match = re.match(
        r"^(?P<agg>SUM|AVG|COUNT)\s*\(\s*(?:DISTINCT\s+)?(?P<col>[A-Za-z_][A-Za-z0-9_]*)\s*\)$",
        stripped,
        re.IGNORECASE,
    )
    if single_match:
        agg = single_match.group("agg").lower()
        col = single_match.group("col")
        dax_func = _AGG_MAP[agg]
        return DaxTranslation(
            expression=f"{dax_func}('{table_name}'[{col}])",
            aggregation=dax_func,
            source_column=col,
            is_currency=col.lower() in _CURRENCY_COLUMN_HINTS,
        )

    raise SQLToDaxError(f"Cannot translate inner expression to basic DAX: {stripped!r}")


def translate(sql_query: str, table_name: str) -> DaxTranslation:
    """
    Translate a KPI's sql_query into a single DAX aggregation expression.
    See module docstring for the full list of recognized shapes.

    Multi-aggregate combinations that are NOT one of the recognized ratio/
    conditional-percentage shapes (e.g. a "top customers" table selecting
    both a COUNT and a SUM as independent output columns) are NOT handled
    here -- callers building a table/tableEx visual should call
    translate_multi() instead. Nested/arithmetic aggregates outside the
    recognized shapes are NOT guessed at -- raises SQLToDaxError.
    """
    stripped = sql_query.strip().rstrip(";").strip()

    # Case 1: ROUND(...) wraps the ENTIRE select expression, no GROUP BY --
    # e.g. "SELECT ROUND(SUM(x)/COUNT(y), 2) AS alias FROM table".
    round_match = _ROUND_WRAPPER_RE.match(stripped)
    if round_match and not re.search(r"GROUP\s+BY", round_match.group("rest") or "", re.IGNORECASE):
        inner_translation = _translate_core(round_match.group("inner").strip(), table_name)
        precision = round_match.group("precision")
        return DaxTranslation(
            expression=f"ROUND({inner_translation.expression}, {precision})",
            aggregation="ROUND",
            source_column=inner_translation.source_column,
            is_currency=inner_translation.is_currency,
            is_percentage=inner_translation.is_percentage,
        )

    # Case 2: a GROUP BY query whose SELECT list has exactly one aggregate
    # expression (optionally ROUND(...)-wrapped) alongside the grouping
    # column(s) -- e.g. "SELECT Dept, ROUND(AVG(x), 2) AS alias FROM table
    # GROUP BY Dept". The grouping column itself is read separately by
    # extract_group_by_column(), not by this function.
    if re.search(r"GROUP\s+BY", stripped, re.IGNORECASE):
        agg_expr = _extract_single_grouped_aggregate_expr(stripped)
        if agg_expr is not None:
            return _translate_expr_maybe_round(agg_expr, table_name)
        raise SQLToDaxError(
            f"Cannot translate SQL to basic DAX (GROUP BY query does not have "
            f"exactly one aggregate expression in its SELECT list -- use "
            f"translate_multi() for multi-measure table KPIs): {sql_query!r}"
        )

    # Case 3: no GROUP BY, no ROUND wrapper -- try COUNT(*), ratio, or a
    # plain single aggregate directly.
    if _COUNT_STAR_RE.match(stripped):
        return DaxTranslation(expression=f"COUNTROWS('{table_name}')", aggregation="COUNTROWS", source_column="*")

    ratio_match = _RATIO_RE.match(stripped)
    if ratio_match:
        return _ratio_from_match(ratio_match, table_name)

    single_match = _SINGLE_AGG_RE.match(stripped)
    if single_match is not None:
        agg = single_match.group("agg").lower()
        col = single_match.group("col")
        dax_func = _AGG_MAP[agg]
        return DaxTranslation(
            expression=f"{dax_func}('{table_name}'[{col}])",
            aggregation=dax_func,
            source_column=col,
            is_currency=col.lower() in _CURRENCY_COLUMN_HINTS,
        )

    if len(list(_GROUPED_AGG_RE.finditer(stripped))) > 1:
        raise SQLToDaxError(
            f"Cannot translate SQL to basic DAX (multiple aggregates in one "
            f"query -- needs more than a single measure): {sql_query!r}"
        )

    raise SQLToDaxError(f"Cannot translate SQL to basic DAX (unsupported shape): {sql_query!r}")


def _translate_expr_maybe_round(expr: str, table_name: str) -> DaxTranslation:
    """Translates a single SELECT-list expression, unwrapping ROUND(...) if present."""
    round_m = re.match(
        r"^ROUND\s*\(\s*(?P<inner>.+?)\s*,\s*(?P<precision>\d+)\s*\)$", expr, re.IGNORECASE | re.DOTALL
    )
    if round_m:
        inner_translation = _translate_core(round_m.group("inner").strip(), table_name)
        return DaxTranslation(
            expression=f"ROUND({inner_translation.expression}, {round_m.group('precision')})",
            aggregation="ROUND",
            source_column=inner_translation.source_column,
            is_currency=inner_translation.is_currency,
            is_percentage=inner_translation.is_percentage,
        )
    return _translate_core(expr, table_name)


def _ratio_from_match(ratio_match, table_name: str) -> DaxTranslation:
    num_func = _AGG_MAP[ratio_match.group("agg1").lower()]
    denom_func = _AGG_MAP[ratio_match.group("agg2").lower()]
    num_col = ratio_match.group("col1")
    denom_col = ratio_match.group("col2")
    expression = (
        f"DIVIDE({num_func}('{table_name}'[{num_col}]), "
        f"{denom_func}('{table_name}'[{denom_col}]))"
    )
    return DaxTranslation(
        expression=expression,
        aggregation="DIVIDE",
        source_column=num_col,
        is_currency=num_col.lower() in _CURRENCY_COLUMN_HINTS,
    )


def _extract_single_grouped_aggregate_expr(stripped: str) -> str | None:
    """
    For a GROUP BY query's SELECT list, finds and returns the text of the
    aggregate expression a single-measure chart (barChart/lineChart) should
    bind to: COUNT(*), SUM(...), AVG(...), COUNT(...), or ROUND(<agg>, n)
    wrapping one of those, INCLUDING the ratio/conditional-percentage
    shapes (SUM(x)/COUNT(y), SUM(CASE WHEN...)*100/COUNT(*)).

    When there's exactly one aggregate expression, returns it directly.
    When there are exactly two AND one of them is a bare COUNT(*)/COUNT(col)
    while the other is a ratio or conditional-percentage expression, returns
    the ratio/percentage one -- this is the "headcount computed alongside a
    rate" pattern (e.g. "COUNT(*) AS total_employees,
    ROUND(...ratio...) AS attrition_rate_pct"), where the KPI's own
    reasoning identifies the rate/percentage as what the chart should plot,
    with the count column present in the query only as supporting context.
    Any other multi-aggregate combination returns None (translate_multi()
    territory, or genuinely ambiguous).
    """
    select_match = re.match(r"^SELECT\s+(?P<cols>.+?)\s+FROM\s", stripped, re.IGNORECASE | re.DOTALL)
    if not select_match:
        return None
    col_list_text = select_match.group("cols")

    items = _split_top_level_commas(col_list_text)
    agg_items = []
    for item in items:
        item = item.strip()
        m = re.match(r"^(?P<expr>(?:ROUND\s*\(.+?,\s*\d+\s*\)|(?:SUM|AVG|COUNT)\s*\(.+?\)))\s+AS\s+\w+$", item, re.IGNORECASE | re.DOTALL)
        if m:
            agg_items.append(m.group("expr").strip())

    if len(agg_items) == 1:
        return agg_items[0]

    if len(agg_items) == 2:
        def _is_bare_count(expr: str) -> bool:
            return bool(re.match(r"^COUNT\s*\(", expr, re.IGNORECASE)) and "/" not in expr and "CASE" not in expr.upper()

        def _is_ratio_or_percentage(expr: str) -> bool:
            # A ratio/percentage expression always contains a "/" (either a
            # direct SUM(x)/COUNT(y) ratio, or the CASE-WHEN percentage
            # idiom's "* 100.0 / COUNT(*)"). A plain SUM(col) or AVG(col)
            # does NOT contain "/" and must NOT be picked here -- picking it
            # would silently choose an unrelated aggregate as "the rate"
            # (e.g. wrongly preferring SUM(Total) over a genuine COUNT(x)
            # in a query that selects two independent, non-ratio aggregates
            # -- that combination is NOT this pattern and must fall through
            # to the multi-aggregate rejection instead).
            return "/" in expr

        bare_counts = [e for e in agg_items if _is_bare_count(e)]
        ratios = [e for e in agg_items if _is_ratio_or_percentage(e)]
        if len(bare_counts) == 1 and len(ratios) == 1 and bare_counts[0] != ratios[0]:
            return ratios[0]

    return None


def _split_top_level_commas(text: str) -> list[str]:
    """Splits on commas that are not nested inside parentheses."""
    parts = []
    depth = 0
    current = []
    for ch in text:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append("".join(current))
            current = []
        else:
            current.append(ch)
    parts.append("".join(current))
    return parts


def translate_multi(sql_query: str, table_name: str) -> list[DaxTranslation]:
    """
    For table/tableEx KPIs that legitimately select more than one aggregate
    as separate output columns -- translate EACH aggregate expression
    (including ROUND(...)-wrapped and COUNT(*) ones) into its own
    DaxTranslation/measure, rather than rejecting the KPI outright.
    """
    select_match = re.match(r"^SELECT\s+(?P<cols>.+?)\s+FROM\s", sql_query.strip(), re.IGNORECASE | re.DOTALL)
    if not select_match:
        raise SQLToDaxError(f"Cannot translate SQL to basic DAX (no SELECT found): {sql_query!r}")

    items = _split_top_level_commas(select_match.group("cols"))
    translations: list[DaxTranslation] = []

    for item in items:
        item = item.strip()
        m = re.match(
            r"^(?P<expr>(?:ROUND\s*\(.+?,\s*\d+\s*\)|(?:SUM|AVG|COUNT)\s*\(.+?\)))\s+AS\s+\w+$",
            item,
            re.IGNORECASE | re.DOTALL,
        )
        if not m:
            continue  # a plain (non-aggregate) grouping column -- skip

        expr = m.group("expr").strip()
        round_m = re.match(r"^ROUND\s*\(\s*(?P<inner>.+?)\s*,\s*(?P<precision>\d+)\s*\)$", expr, re.IGNORECASE | re.DOTALL)
        if round_m:
            inner_translation = _translate_core(round_m.group("inner").strip(), table_name)
            translations.append(
                DaxTranslation(
                    expression=f"ROUND({inner_translation.expression}, {round_m.group('precision')})",
                    aggregation="ROUND",
                    source_column=inner_translation.source_column,
                    is_currency=inner_translation.is_currency,
                    is_percentage=inner_translation.is_percentage,
                )
            )
        else:
            translations.append(_translate_core(expr, table_name))

    if not translations:
        raise SQLToDaxError(
            f"Cannot translate SQL to basic DAX (no aggregate calls found): {sql_query!r}"
        )
    return translations


def extract_group_by_column(sql_query: str) -> str | None:
    """
    For chart-type KPIs (barChart/lineChart/table), the KPI's SQL typically
    GROUPs BY a category/date column -- that's the column the visual's
    Category/Rows role binds to. Returns the bare column name being grouped
    on, or None if there's no GROUP BY (e.g. a plain card-style aggregate).

    Handles two shapes:
      - GROUP BY <Column>                        -> "Column"
      - GROUP BY strftime('<fmt>', <Column>)      -> "Column" (innermost arg,
        not the function name -- this is the date-truncation pattern the
        Domain/KPI node uses for "Monthly X Trend" style KPIs)
    """
    match = re.search(
        r"GROUP\s+BY\s+(?P<expr>.+?)(?:\s+ORDER\s+BY|\s+LIMIT|\s*$)",
        sql_query,
        re.IGNORECASE | re.DOTALL,
    )
    if not match:
        return None
    expr = match.group("expr").strip()

    func_call = re.match(r"^\w+\s*\((?P<args>.+)\)\s*$", expr)
    if func_call:
        args = func_call.group("args")
        idents = re.findall(r"[A-Za-z_][A-Za-z0-9_]*", args)
        return idents[-1] if idents else None

    plain_match = re.match(r"^([A-Za-z_][A-Za-z0-9_]*)$", expr)
    return plain_match.group(1) if plain_match else None


# =====================================================================
# Page-grouping and canvas layout
#
# Grouping rule (per the agreed plan): cards are small and fit up to 3
# per page; chart/table visuals need more room and fit up to 2 per
# page. Greedily bucket cards separately from chart/table types, fill
# pages up to their cap, and merge a trailing under-filled page forward
# so no page (other than possibly the very first, if there's only one
# KPI total) ends up with fewer than 2 visuals when more than one page
# would otherwise exist.
#
# Canvas: standard 1280x720 (§2.7). Layout uses a simple non-overlapping
# grid; Position values are unconstrained floats per §2.8, so any
# non-overlapping placement is valid -- exact pixel aesthetics aren't a
# compiler concern here.
# =====================================================================

CANVAS_WIDTH = 1280
CANVAS_HEIGHT = 720
CARDS_PER_PAGE = 3
CHARTS_PER_PAGE = 2

_CARD_TYPES = {"card"}
_WIDE_TYPES = {"barChart", "lineChart", "table"}


def group_into_pages(visuals: Sequence[Visual]) -> List[List[Visual]]:
    """
    Buckets visuals (already built, without final position) into page-sized
    groups. Returns a list of visual-lists; caller assigns page display
    names and calls layout_page() to set final positions.
    """
    cards = [v for v in visuals if v.chart_type in _CARD_TYPES]
    wide = [v for v in visuals if v.chart_type in _WIDE_TYPES]

    pages: List[List[Visual]] = []
    for i in range(0, len(cards), CARDS_PER_PAGE):
        pages.append(cards[i : i + CARDS_PER_PAGE])
    for i in range(0, len(wide), CHARTS_PER_PAGE):
        pages.append(wide[i : i + CHARTS_PER_PAGE])

    # Merge a trailing under-filled page (fewer than 2 visuals) into the
    # previous page, as long as doing so doesn't push that page over its
    # type's own cap and there's more than one page to merge into.
    if len(pages) > 1 and len(pages[-1]) < 2:
        last = pages[-1]
        prev = pages[-2]
        cap = CARDS_PER_PAGE if all(v.chart_type in _CARD_TYPES for v in last) else CHARTS_PER_PAGE
        if len(prev) + len(last) <= max(cap, CARDS_PER_PAGE):
            pages[-2] = prev + last
            pages.pop()

    return pages


def layout_page(visuals: Sequence[Visual]) -> None:
    """
    Mutates each Visual's .position in place for a single page, arranging
    them left-to-right in one row if they fit, else wrapping to a second row.
    Cards get smaller boxes than charts/tables since more of them share a page.
    """
    n = len(visuals)
    if n == 0:
        return

    is_card_page = all(v.chart_type in _CARD_TYPES for v in visuals)

    if is_card_page:
        # Up to 3 cards, single row, evenly spaced.
        card_width = CANVAS_WIDTH // n
        card_height = 200
        for i, v in enumerate(visuals):
            v.position = Position(
                x=i * card_width,
                y=40,
                z=i * 1000,
                width=card_width - 20,
                height=card_height,
                tab_order=i,
            )
        return

    # Chart/table pages: up to 2 side by side; if 3 (after a merge), 2 on
    # top row + 1 centered on a second row.
    if n <= 2:
        width = CANVAS_WIDTH // n
        height = CANVAS_HEIGHT - 40
        for i, v in enumerate(visuals):
            v.position = Position(
                x=i * width,
                y=0,
                z=i * 1000,
                width=width - 10,
                height=height,
                tab_order=i,
            )
    else:
        # 3 visuals: 2 on top row, 1 centered below.
        top_width = CANVAS_WIDTH // 2
        top_height = CANVAS_HEIGHT // 2
        for i in range(2):
            visuals[i].position = Position(
                x=i * top_width,
                y=0,
                z=i * 1000,
                width=top_width - 10,
                height=top_height - 10,
                tab_order=i,
            )
        visuals[2].position = Position(
            x=CANVAS_WIDTH // 4,
            y=top_height,
            z=2000,
            width=top_width - 10,
            height=top_height - 10,
            tab_order=2,
        )


