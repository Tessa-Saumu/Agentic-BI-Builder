# =====================================================================
# SQL normalization helpers (bug fixes 7.1a / 7.1b)
#
# Two small, general text-level normalizations applied BEFORE any shape
# regex runs, so the many shape-matchers above (which all assume a bare
# "[A-Za-z_][A-Za-z0-9_]*" identifier and an aggregate call sitting at
# the very start of an expression) keep working completely unchanged
# against SQL that is merely STYLED differently, not structurally
# different. Neither of these teaches the translator any new DAX shape
# -- they only strip cosmetic variation (quoting, defensive grouping
# parens) that was defeating the existing shape-matchers before they
# even got a chance to run.
# =====================================================================

# ANSI-style double-quoted identifier, e.g. "Total" -> Total.
_QUOTED_IDENTIFIER_RE = re.compile(r'"([A-Za-z_][A-Za-z0-9_]*)"')

# T-SQL-style bracket-quoted identifier, e.g. [Total] -> Total. Observed in
# real LLM output during PROJECT_EVIDENCE verification; SQLite itself
# accepts this quoting natively, so only the translator (whose regexes all
# assume bare identifiers) needs the normalization -- the executor and the
# column validator already handle bracketed SQL unchanged.
_BRACKET_IDENTIFIER_RE = re.compile(r"\[([A-Za-z_][A-Za-z0-9_]*)\]")

# Single-quoted SQL string literal -- used to split the query so identifier
# normalization below never rewrites literal contents (e.g. a comparison
# value like '[North]' must keep its brackets; only real identifiers lose
# theirs).
_STRING_LITERAL_SPLIT_RE = re.compile(r"('[^']*')")


def _normalize_identifiers(sql_query: str) -> str:
    """
    Strips ANSI-style double-quoted identifiers down to their bare form,
    e.g. SELECT SUM("Total") FROM data -> SELECT SUM(Total) FROM data,
    and likewise T-SQL-style bracket-quoted identifiers ([Total] -> Total).

    BUG FIX (7.1a): one dataset's KPI file was regenerated using
    double-quoted identifiers for every column reference (SUM("Total"),
    GROUP BY "BillingCountry", etc.) -- a different SQL quoting style
    than every regex in this module was written against, all of which
    match bare identifiers only. Rather than teach each individual
    shape-matching regex to separately tolerate an optional pair of
    quotes, normalize once, up front: every downstream regex then sees
    exactly the same bare-identifier text it already expects, regardless
    of which quoting style the upstream LLM used this run. Applied at
    the top of every public entry point (translate, translate_multi,
    extract_group_by_column) so it takes effect no matter which one a
    caller reaches first -- each is called independently by
    builder._build_measures_and_group_cols, not chained through a single
    shared preprocessing step.

    Single-quoted string literals are left completely untouched (SQLite
    uses single quotes for string values, so Attrition = 'Yes' and
    strftime('%Y-%m', ...) pass through unchanged) -- normalization
    applies only to the text outside them.
    """
    segments = _STRING_LITERAL_SPLIT_RE.split(sql_query)
    for i in range(0, len(segments), 2):  # even indices: outside any literal
        segments[i] = _QUOTED_IDENTIFIER_RE.sub(r"\1", segments[i])
        segments[i] = _BRACKET_IDENTIFIER_RE.sub(r"\1", segments[i])
    return "".join(segments)


def _strip_enclosing_parens(expr: str) -> str:
    """
    Strips one layer of fully-wrapping, semantically-redundant outer
    parentheses from `expr` if present, e.g. "(SUM(x) / COUNT(y))" ->
    "SUM(x) / COUNT(y)". Recurses to peel multiple redundant layers,
    e.g. "((x))" -> "x". No-ops (returns expr unchanged) when there is
    no wrap, or when the leading "(" is NOT matched by the trailing ")"
    -- i.e. it closes somewhere in the middle, as in "(a) + (b)", where
    stripping would corrupt the expression, so it is correctly left
    alone (checked via paren-depth tracking, not just first/last char).

    BUG FIX (7.1b): an LLM-generated ratio/percentage expression is
    sometimes defensively wrapped in an outer pair of parens for
    precedence clarity -- e.g. "(SUM(CASE WHEN col = 'val' THEN 1 ELSE 0
    END) * 100.0 / COUNT(*))" -- which is semantically identical to the
    unwrapped form but defeats every shape-matcher below: they all
    expect the expression to start directly with SUM/AVG/COUNT, and
    _try_ratio's paren-depth tracking expects the real top-level "/" to
    actually sit at depth 0, which an outer wrap prevents (the "/" ends
    up at depth 1 instead, so _split_top_level_operator never finds it).
    Stripping the redundant wrap here -- once, centrally, as the first
    step of _translate_core -- means every existing shape below keeps
    working completely unchanged on the unwrapped text.
    """
    stripped = expr.strip()
    if not (stripped.startswith("(") and stripped.endswith(")")):
        return stripped
    depth = 0
    for i, ch in enumerate(stripped):
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
            if depth == 0 and i != len(stripped) - 1:
                return stripped  # closes before the end -- not a true outer wrap
    return _strip_enclosing_parens(stripped[1:-1])


def _unwrap_item_parens(item: str) -> str:
    """
    For a single SELECT-list "<expr> AS <alias>" entry, strips one layer
    of redundant fully-wrapping parens from <expr>, using the identical
    rule as _strip_enclosing_parens (which this delegates to) -- e.g.
    "(SUM(x) * 100.0 / COUNT(*)) AS pct" -> "SUM(x) * 100.0 / COUNT(*)
    AS pct". This lets the aggregate-shape regex in
    _extract_single_grouped_aggregate_expr / translate_multi (which
    requires an item to start directly with ROUND/SUM/AVG/COUNT) still
    recognize an item that is really just one of those shapes wearing a
    defensive outer paren -- without it, such an item is silently
    treated as "not an aggregate" and dropped from consideration
    entirely (see 7.1b). No-op if `item` has no "AS <alias>" suffix, or
    its expression part isn't fully wrapped.
    """
    m = re.match(r"^(?P<expr>.+?)\s+AS\s+(?P<alias>\w+)$", item, re.IGNORECASE | re.DOTALL)
    if not m:
        return item
    unwrapped = _strip_enclosing_parens(m.group("expr"))
    return f"{unwrapped} AS {m.group('alias')}"


def _strip_where_clause(sql_query: str) -> tuple[str, str | None]:
    """
    Extracts a single WHERE condition from `sql_query` and returns
    (sql_without_where, condition_or_None).

    "1=1" is treated as a no-op filter (SQL idiom for "always true", seen
    in one of online_retail's KPIs before Reflector correction) and
    returned as condition=None -- it adds nothing to translate as DAX.

    Only ONE simple condition is recognized: a "<column> <op> <value>"
    comparison (matching every real WHERE across the 3 datasets' KPIs,
    e.g. "Quantity > 0") or a "<column> IS [NOT] NULL" null check (e.g.
    the historical "Total Unique Customers" KPI's "CustomerID IS NOT
    NULL"). Anything else -- an AND/OR-joined multi-condition WHERE, a
    function call in the condition, etc. -- is returned as
    "__UNRECOGNIZED__" so the caller raises the standard "unsupported
    shape" error, rather than silently dropping a filter condition the
    compiler doesn't actually understand.
    """
    match = _WHERE_CLAUSE_RE.search(sql_query)
    if not match:
        # No recognized WHERE form -- but a WHERE keyword may still be
        # present in an unrecognized form (e.g. AND-joined conditions the
        # regex above couldn't match). On a GROUP BY query that leftover
        # WHERE would otherwise be silently dropped: the GROUP BY path
        # parses only the SELECT list, so it would translate the measure
        # as if the filter didn't exist. Fail closed instead. String
        # literals are excluded from the check so a value like 'somewhere'
        # (matched only via a real word boundary) or a literal containing
        # the word WHERE can never trip it.
        without_literals = _STRING_LITERAL_SPLIT_RE.sub("''", sql_query)
        if re.search(r"\bWHERE\b", without_literals, re.IGNORECASE):
            return sql_query, "__UNRECOGNIZED__"
        return sql_query, None

    condition_text = match.group("condition").strip()
    trailing = (match.group("trailing") or "").strip()

    if re.match(r"^1\s*=\s*1$", condition_text, re.IGNORECASE):
        condition = None
    else:
        cond_match = _CONDITION_RE.match(condition_text)
        if cond_match is None:
            # A condition shape we don't recognize (e.g. involves a
            # function call, an AND/OR, or a form _CONDITION_RE doesn't
            # match) -- leave the SQL untouched so it falls through to the
            # normal unsupported-shape error instead of guessing.
            return sql_query, "__UNRECOGNIZED__"
        col = cond_match.group("col")
        if cond_match.group("op") is None:
            # "<column> IS [NOT] NULL" null-check form.
            op = "IS NOT NULL" if cond_match.group("null_not") else "IS NULL"
            condition = f"col::{col}::{op}::"
            without_where = sql_query[: match.start()] + (f" {trailing}" if trailing else "")
            return without_where.strip(), condition
        op = _SQL_TO_DAX_OP.get(cond_match.group("op"))
        if op is None:
            return sql_query, "__UNRECOGNIZED__"
        val = cond_match.group("val")
        # Numeric values are embedded bare; anything else is treated as a
        # DAX string literal (double-quoted). Every WHERE seen so far
        # compares against a bare number (e.g. "Quantity > 0").
        try:
            float(val)
            dax_val = val
        except ValueError:
            dax_val = f'"{val}"'
        condition = f"col::{col}::{op}::{dax_val}"

    without_where = sql_query[: match.start()] + (f" {trailing}" if trailing else "")
    return without_where.strip(), condition


def _apply_where_filter(translation: DaxTranslation, condition: str | None, table_name: str) -> DaxTranslation:
    """
    Wraps an already-translated DaxTranslation in DAX CALCULATE(...) if
    `condition` is a real (recognized) filter condition. condition is the
    "col::name::op::value" encoding produced by _strip_where_clause; see
    that function's docstring for what forms are recognized.
    """
    if condition is None:
        return translation
    if condition == "__UNRECOGNIZED__":
        raise SQLToDaxError(
            "WHERE clause present but its condition shape is not recognized "
            "(only a single 'column OP value' comparison or a single "
            "'column IS [NOT] NULL' check is supported)."
        )
    _, col, op, val = condition.split("::")
    if op in ("IS NULL", "IS NOT NULL"):
        # SQL null check -> DAX blank comparison, e.g. the historical
        # "Total Unique Customers" KPI: COUNT(DISTINCT CustomerID) ...
        # WHERE CustomerID IS NOT NULL -> CALCULATE(DISTINCTCOUNT(
        # 'data'[CustomerID]), 'data'[CustomerID] <> BLANK()).
        dax_comparison = "= BLANK()" if op == "IS NULL" else "<> BLANK()"
        wrapped = f"CALCULATE({translation.expression}, '{table_name}'[{col}] {dax_comparison})"
    else:
        wrapped = f"CALCULATE({translation.expression}, '{table_name}'[{col}] {op} {val})"
    return DaxTranslation(
        expression=wrapped,
        aggregation=translation.aggregation,
        source_column=translation.source_column,
        is_currency=translation.is_currency,
        is_percentage=translation.is_percentage,
    )


def _translate_core(stripped: str, table_name: str) -> DaxTranslation:
    """
    Translates a SELECT expression's core aggregate shape (no ROUND
    wrapper, no GROUP BY concerns -- those are handled by the callers).
    Tries, in order: conditional-count-percentage, ratio, COUNT(*),
    COUNT(DISTINCT col), row-wise product (SUM/AVG(colA * colB)), plain
    single aggregate.
    """
    # BUG FIX (7.1b): strip a redundant fully-wrapping outer paren first
    # (no-op if there isn't one) -- see _strip_enclosing_parens docstring.
    # Needed here (not just at the item-splitting level in
    # _extract_single_grouped_aggregate_expr/translate_multi) because a
    # no-GROUP-BY query's single SELECT expression reaches _translate_core
    # directly, wrapping parens and all, via _translate_without_where's
    # Case 3 select_match.
    stripped = _strip_enclosing_parens(stripped)

    cond_match = _match_conditional_pct(stripped)
    if cond_match:
        col, val = cond_match
        expression = (
            f"DIVIDE(COUNTROWS(FILTER('{table_name}', '{table_name}'[{col}] = \"{val}\")), "
            f"COUNTROWS('{table_name}')) * 100"
        )
        return DaxTranslation(
            expression=expression,
            aggregation="DIVIDE",
            source_column=col,
            is_percentage=True,
        )

    # IMPORTANT ORDERING: the conditional-percentage check above must run
    # BEFORE this ratio check, since that pattern's own expression contains
    # a top-level "/" too (SUM(CASE WHEN...) * 100.0 / COUNT(*)) -- if the
    # ratio check ran first, it would incorrectly split that expression on
    # its "/" and produce a plain DIVIDE(SUM(...), COUNT(*)) instead of the
    # correct FILTER/COUNTROWS percentage idiom. _try_ratio recursively
    # translates each side via _translate_core, so it composes with every
    # other shape below it (SUMX/AVERAGEX products, DISTINCTCOUNT, plain
    # aggregates) -- e.g. online_retail's AOV: SUM(Quantity * UnitPrice) /
    # COUNT(DISTINCT InvoiceNo).
    ratio_translation = _try_ratio(stripped, table_name)
    if ratio_translation is not None:
        return ratio_translation

    count_star_match = re.match(r"^COUNT\s*\(\s*\*\s*\)$", stripped, re.IGNORECASE)
    if count_star_match:
        return DaxTranslation(
            expression=f"COUNTROWS('{table_name}')",
            aggregation="COUNTROWS",
            source_column="*",
        )

    # BUG FIX (2026-07-12): must be checked BEFORE the plain single-aggregate
    # match below, whose regex's optional "(?:DISTINCT\s+)?" group matched
    # COUNT(DISTINCT col) too but then silently discarded the DISTINCT
    # keyword, translating it as plain COUNT('table'[col]) -- counting
    # every row (including duplicates) instead of distinct values. Real
    # DAX has a dedicated function for this (DISTINCTCOUNT), which is the
    # only correct translation; a plain COUNT is not equivalent and would
    # silently produce a wrong number for online_retail's Average Order
    # Value KPI (COUNT(DISTINCT InvoiceNo) -- unique orders, not line-item
    # rows).
    distinct_count_match = _DISTINCT_COUNT_RE.match(stripped)
    if distinct_count_match:
        col = distinct_count_match.group("col")
        return DaxTranslation(
            expression=f"DISTINCTCOUNT('{table_name}'[{col}])",
            aggregation="DISTINCTCOUNT",
            source_column=col,
        )

    # GENERAL CASE WHEN -> IF translation (2026-07-13): SUM/AVG wrapping a
    # CASE WHEN that is NOT the specific 0/1-count-percentage idiom above
    # (e.g. "SUM(CASE WHEN Total > 50 THEN Total ELSE 0 END)" -- a
    # conditional SUM, not a percentage). Checked after the percentage
    # idiom (more specific, wins when it matches) and before the plain
    # single-aggregate match (whose regex wouldn't match "CASE WHEN..."
    # as a column name anyway, but this is checked first for clarity).
    # DAX has no CASE WHEN in expression position -- the correct
    # translation is the row-context iterator SUMX/AVERAGEX wrapping a
    # per-row IF(...), the same pattern as the SUMX/AVERAGEX row-wise
    # product support above.
    case_wrapped_match = re.match(
        r"^(?P<agg>SUM|AVG)\s*\(\s*(?P<case_expr>CASE\s+WHEN\s+.+?\s+END)\s*\)$",
        stripped,
        re.IGNORECASE | re.DOTALL,
    )
    if case_wrapped_match:
        dax_if = _case_when_to_dax_if(case_wrapped_match.group("case_expr"), table_name)
        if dax_if is not None:
            agg = case_wrapped_match.group("agg").lower()
            dax_func = _ROWWISE_AGG_MAP[agg]
            return DaxTranslation(
                expression=f"{dax_func}('{table_name}', {dax_if})",
                aggregation=dax_func,
                source_column="__case_when__",
            )

    # A bare CASE WHEN, with no surrounding SUM/AVG at all -- translates
    # directly to DAX IF(...), no row-context iterator needed since there's
    # no aggregation wrapping it.
    if stripped.upper().startswith("CASE"):
        dax_if = _case_when_to_dax_if(stripped, table_name)
        if dax_if is not None:
            return DaxTranslation(
                expression=dax_if,
                aggregation="IF",
                source_column="__case_when__",
            )

    # SCOPE EXTENSION (2026-07-12): SUM(ColA * ColB) / AVG(ColA * ColB) --
    # see the _ROWWISE_PRODUCT_RE / _ROWWISE_AGG_MAP comment above for why
    # this needs SUMX/AVERAGEX rather than a plain SUM/AVERAGE. Must be
    # checked before the plain single-aggregate match below, since that
    # regex's column-name group would not match "ColA * ColB" anyway (no
    # silent-wrong-answer risk here, just ordering for clarity).
    rowwise_match = _ROWWISE_PRODUCT_RE.match(stripped)
    if rowwise_match:
        agg = rowwise_match.group("agg").lower()
        col1 = rowwise_match.group("col1")
        col2 = rowwise_match.group("col2")
        dax_func = _ROWWISE_AGG_MAP[agg]
        expression = (
            f"{dax_func}('{table_name}', '{table_name}'[{col1}] * '{table_name}'[{col2}])"
        )
        # Currency-hint on a product like Quantity * UnitPrice: flag as
        # currency if either operand column name suggests money (a
        # quantity-times-price product is a monetary total even though
        # neither individual column alone might match every heuristic).
        is_currency = (
            col1.lower() in _CURRENCY_COLUMN_HINTS or col2.lower() in _CURRENCY_COLUMN_HINTS
        )
        return DaxTranslation(
            expression=expression,
            aggregation=dax_func,
            source_column=f"{col1}_{col2}",
            is_currency=is_currency,
        )

    single_match = re.match(
        r"^(?P<agg>SUM|AVG|COUNT)\s*\(\s*(?P<col>[A-Za-z_][A-Za-z0-9_]*)\s*\)$",
        stripped,
        re.IGNORECASE,
    )
    if single_match:
        agg = single_match.group("agg").lower()
        col = single_match.group("col")
        dax_func = _AGG_MAP[agg]
        return DaxTranslation(
            expression=f"{dax_func}('{table_name}'[{col}])",
            aggregation=dax_func,
            source_column=col,
            is_currency=col.lower() in _CURRENCY_COLUMN_HINTS,
        )

    raise SQLToDaxError(f"Cannot translate inner expression to basic DAX: {stripped!r}")


def translate(sql_query: str, table_name: str) -> DaxTranslation:
    """
    Translate a KPI's sql_query into a single DAX aggregation expression.
    See module docstring for the full list of recognized shapes.

    A WHERE clause (if present) is stripped before the rest of the
    translation logic runs, then re-applied at the end as a DAX
    CALCULATE(...) filter wrapping the final expression -- e.g.
    online_retail's "Total Revenue": SELECT SUM(Quantity * UnitPrice) AS
    total_revenue FROM data WHERE Quantity > 0 -> CALCULATE(SUMX('data',
    'data'[Quantity] * 'data'[UnitPrice]), 'data'[Quantity] > 0).
    """
    sql_query = _normalize_identifiers(sql_query)  # bug fix 7.1a
    sql_without_where, condition = _strip_where_clause(sql_query)
    translation = _translate_without_where(sql_without_where, table_name, original_sql=sql_query)
    return _apply_where_filter(translation, condition, table_name)


def _translate_without_where(sql_query: str, table_name: str, original_sql: str | None = None) -> DaxTranslation:
    """
    The original translate() logic, operating on SQL with any WHERE clause
    already stripped by the public translate() wrapper above.

    Multi-aggregate combinations that are NOT one of the recognized ratio/
    conditional-percentage shapes (e.g. a "top customers" table selecting
    both a COUNT and a SUM as independent output columns) are NOT handled
    here -- callers building a table/tableEx visual should call
    translate_multi() instead. Nested/arithmetic aggregates outside the
    recognized shapes are NOT guessed at -- raises SQLToDaxError.
    """
    error_sql = original_sql if original_sql is not None else sql_query
    stripped = sql_query.strip().rstrip(";").strip()

    # Case 1: ROUND(...) wraps the ENTIRE select expression, no GROUP BY --
    # e.g. "SELECT ROUND(SUM(x)/COUNT(y), 2) AS alias FROM table".
    round_match = _ROUND_WRAPPER_RE.match(stripped)
    if round_match and not re.search(r"GROUP\s+BY", round_match.group("rest") or "", re.IGNORECASE):
        inner_translation = _translate_core(round_match.group("inner").strip(), table_name)
        precision = round_match.group("precision")
        return DaxTranslation(
            expression=f"ROUND({inner_translation.expression}, {precision})",
            aggregation="ROUND",
            source_column=inner_translation.source_column,
            is_currency=inner_translation.is_currency,
            is_percentage=inner_translation.is_percentage,
        )

    # Case 2: a GROUP BY query whose SELECT list has exactly one aggregate
    # expression (optionally ROUND(...)-wrapped) alongside the grouping
    # column(s) -- e.g. "SELECT Dept, ROUND(AVG(x), 2) AS alias FROM table
    # GROUP BY Dept". The grouping column itself is read separately by
    # extract_group_by_column(), not by this function.
    if re.search(r"GROUP\s+BY", stripped, re.IGNORECASE):
        agg_expr = _extract_single_grouped_aggregate_expr(stripped)
        if agg_expr is not None:
            return _translate_expr_maybe_round(agg_expr, table_name)
        raise SQLToDaxError(
            f"Cannot translate SQL to basic DAX (GROUP BY query does not have "
            f"exactly one aggregate expression in its SELECT list -- use "
            f"translate_multi() for multi-measure table KPIs): {error_sql!r}"
        )

    # Case 3: no GROUP BY, no ROUND wrapper. Extract the single SELECT-list
    # expression (there is exactly one column selected in this shape --
    # "SELECT <expr> AS alias FROM table", no grouping columns alongside
    # it) and delegate to _translate_core, which tries (in order)
    # conditional-percentage, ratio, COUNT(*), COUNT(DISTINCT col),
    # row-wise product (SUMX/AVERAGEX), then a plain single aggregate.
    # Delegating here (rather than duplicating each of those checks a
    # second time) is what lets a bare, non-ratio SUM(ColA * ColB) --
    # e.g. online_retail's "Total Revenue": SUM(Quantity * UnitPrice), no
    # GROUP BY, no ratio -- resolve correctly instead of only being
    # reachable through the ROUND-wrapper or GROUP-BY paths.
    select_match = re.match(r"^SELECT\s+(?P<expr>.+?)\s+AS\s+\w+\s+FROM\s+[A-Za-z_][A-Za-z0-9_]*\s*$", stripped, re.IGNORECASE | re.DOTALL)
    if select_match is not None:
        try:
            return _translate_core(select_match.group("expr").strip(), table_name)
        except SQLToDaxError:
            pass

    if len(list(_GROUPED_AGG_RE.finditer(stripped))) > 1:
        raise SQLToDaxError(
            f"Cannot translate SQL to basic DAX (multiple aggregates in one "
            f"query -- needs more than a single measure): {error_sql!r}"
        )

    raise SQLToDaxError(f"Cannot translate SQL to basic DAX (unsupported shape): {error_sql!r}")


def _translate_expr_maybe_round(expr: str, table_name: str) -> DaxTranslation:
    """Translates a single SELECT-list expression, unwrapping ROUND(...) if present."""
    round_m = re.match(
        r"^ROUND\s*\(\s*(?P<inner>.+?)\s*,\s*(?P<precision>\d+)\s*\)$", expr, re.IGNORECASE | re.DOTALL
    )
    if round_m:
        inner_translation = _translate_core(round_m.group("inner").strip(), table_name)
        return DaxTranslation(
            expression=f"ROUND({inner_translation.expression}, {round_m.group('precision')})",
            aggregation="ROUND",
            source_column=inner_translation.source_column,
            is_currency=inner_translation.is_currency,
            is_percentage=inner_translation.is_percentage,
        )
    return _translate_core(expr, table_name)


def _split_top_level_operator(text: str, operator: str) -> tuple[str, str] | None:
    """
    Splits `text` on the first occurrence of `operator` that is NOT nested
    inside parentheses. Returns (left, right) with both sides stripped, or
    None if the operator never appears at paren-depth 0. Used to detect a
    ratio's "/" without false-matching a "/" that might appear inside a
    function call's arguments (none currently do, but this is more robust
    than a regex that assumes the "/" is always at the top level).
    """
    depth = 0
    for i, ch in enumerate(text):
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        elif ch == operator and depth == 0:
            return text[:i].strip(), text[i + 1 :].strip()
    return None


def _try_ratio(expr: str, table_name: str) -> DaxTranslation | None:
    """
    If `expr` is <left> / <right> at the top level, recursively translates
    both sides via _translate_core and combines them with DAX DIVIDE(...).
    Returns None (not a ratio) if there's no top-level "/". This replaces
    the old regex-only ratio matcher so a ratio's operands can be ANY
    recognized _translate_core shape -- plain aggregate, SUMX/AVERAGEX
    product, or DISTINCTCOUNT -- not just a bare-column aggregate.
    """
    split = _split_top_level_operator(expr, "/")
    if split is None:
        return None
    left, right = split
    num = _translate_core(left, table_name)
    denom = _translate_core(right, table_name)
    return DaxTranslation(
        expression=f"DIVIDE({num.expression}, {denom.expression})",
        aggregation="DIVIDE",
        source_column=num.source_column,
        is_currency=num.is_currency,
    )


def _extract_single_grouped_aggregate_expr(stripped: str) -> str | None:
    """
    For a GROUP BY query's SELECT list, finds and returns the text of the
    aggregate expression a single-measure chart (barChart/lineChart) should
    bind to: COUNT(*), SUM(...), AVG(...), COUNT(...), or ROUND(<agg>, n)
    wrapping one of those, INCLUDING the ratio/conditional-percentage
    shapes (SUM(x)/COUNT(y), SUM(CASE WHEN...)*100/COUNT(*)).

    When there's exactly one aggregate expression, returns it directly.
    When there are exactly two AND one of them is a bare COUNT(*)/COUNT(col)
    while the other is a ratio or conditional-percentage expression, returns
    the ratio/percentage one -- this is the "headcount computed alongside a
    rate" pattern (e.g. "COUNT(*) AS total_employees,
    ROUND(...ratio...) AS attrition_rate_pct"), where the KPI's own
    reasoning identifies the rate/percentage as what the chart should plot,
    with the count column present in the query only as supporting context.
    Any other multi-aggregate combination returns None (translate_multi()
    territory, or genuinely ambiguous).

    GENERALIZED (bug fix 7.1b): originally this "pick the rate, ignore its
    supporting counts" rule only fired for exactly 2 agg_items (one bare
    count + one ratio). That was too narrow for a query that selects a rate
    ALONGSIDE more than one raw supporting aggregate -- e.g. COUNT(*) AS
    total, SUM(CASE WHEN...) AS raw_numerator, (SUM(CASE WHEN...) * 100.0 /
    COUNT(*)) AS rate is 3 agg_items once the wrapped rate expression is
    unwrapped and recognized (see _unwrap_item_parens) -- so the rule below
    now fires for ANY number of agg_items, as long as EXACTLY ONE of them
    is a ratio/percentage expression (contains a top-level "/"). Zero or
    2+ ratio items among agg_items is unchanged: still falls through to
    None as genuinely ambiguous, same as before.
    """
    select_match = re.match(r"^SELECT\s+(?P<cols>.+?)\s+FROM\s", stripped, re.IGNORECASE | re.DOTALL)
    if not select_match:
        return None
    col_list_text = select_match.group("cols")

    items = _split_top_level_commas(col_list_text)
    agg_items = []
    for item in items:
        # bug fix 7.1b: unwrap a redundant outer paren before classifying
        # the item -- see _unwrap_item_parens.
        item = _unwrap_item_parens(item.strip())

        # Conditional-percentage idiom, checked first: its CAST-wrapped
        # phrasing starts with "(CAST(...", not a bare SUM/AVG/COUNT/ROUND,
        # so the general aggregate-prefix match below would never
        # recognize it as an aggregate item at all.
        alias_match = re.match(r"^(?P<expr>.+?)\s+AS\s+\w+$", item, re.IGNORECASE | re.DOTALL)
        if alias_match and _match_conditional_pct(alias_match.group("expr")):
            agg_items.append(alias_match.group("expr").strip())
            continue

        m = re.match(r"^(?P<expr>(?:ROUND\s*\(.+?,\s*\d+\s*\)|(?:SUM|AVG|COUNT)\s*\(.+?\)))\s+AS\s+\w+$", item, re.IGNORECASE | re.DOTALL)
        if m:
            agg_items.append(m.group("expr").strip())

    if len(agg_items) == 1:
        return agg_items[0]

    if len(agg_items) >= 2:
        # A ratio/percentage expression always contains a "/" (either a
        # direct SUM(x)/COUNT(y) ratio, or the CASE-WHEN percentage idiom's
        # "* 100.0 / COUNT(*)"). A plain SUM(col)/AVG(col)/COUNT(col) does
        # NOT contain "/" and must NOT be picked here -- picking one would
        # silently choose an unrelated aggregate as "the rate" (e.g.
        # wrongly preferring SUM(Total) over a genuine COUNT(x) when the
        # query actually selects two independent, non-ratio aggregates --
        # that combination is NOT this pattern and must still fall through
        # to the multi-aggregate rejection below).
        ratios = [e for e in agg_items if "/" in e]
        if len(ratios) == 1:
            return ratios[0]

    return None


def _split_top_level_commas(text: str) -> list[str]:
    """Splits on commas that are not nested inside parentheses."""
    parts = []
    depth = 0
    current = []
    for ch in text:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append("".join(current))
            current = []
        else:
            current.append(ch)
    parts.append("".join(current))
    return parts


def translate_multi(sql_query: str, table_name: str) -> list[DaxTranslation]:
    """
    For table/tableEx KPIs that legitimately select more than one aggregate
    as separate output columns -- translate EACH aggregate expression
    (including ROUND(...)-wrapped and COUNT(*) ones) into its own
    DaxTranslation/measure, rather than rejecting the KPI outright.

    A WHERE clause (if present) is stripped before parsing the SELECT
    list, then re-applied as a DAX CALCULATE(...) filter around EVERY
    resulting measure -- e.g. online_retail's "Top 10 Products by Quantity
    Sold": ...FROM data WHERE Quantity > 0 GROUP BY StockCode, Description
    -> both total_quantity_sold and revenue_contribution get wrapped in
    CALCULATE(..., 'data'[Quantity] > 0), since the filter applies to the
    whole query, not just one of its several aggregate columns.
    """
    sql_query = _normalize_identifiers(sql_query)  # bug fix 7.1a
    sql_without_where, condition = _strip_where_clause(sql_query)

    select_match = re.match(r"^SELECT\s+(?P<cols>.+?)\s+FROM\s", sql_without_where.strip(), re.IGNORECASE | re.DOTALL)
    if not select_match:
        raise SQLToDaxError(f"Cannot translate SQL to basic DAX (no SELECT found): {sql_query!r}")

    items = _split_top_level_commas(select_match.group("cols"))
    translations: list[DaxTranslation] = []

    for item in items:
        # bug fix 7.1b: unwrap a redundant outer paren before classifying
        # the item, so e.g. "(SUM(x) * 100.0 / COUNT(*)) AS pct" is still
        # recognized as an aggregate expression instead of silently
        # skipped as "not an aggregate" (see _unwrap_item_parens).
        item = _unwrap_item_parens(item.strip())
        m = re.match(
            r"^(?P<expr>(?:ROUND\s*\(.+?,\s*\d+\s*\)|(?:SUM|AVG|COUNT)\s*\(.+?\)))\s+AS\s+\w+$",
            item,
            re.IGNORECASE | re.DOTALL,
        )
        if not m:
            continue  # a plain (non-aggregate) grouping column -- skip

        expr = m.group("expr").strip()
        round_m = re.match(r"^ROUND\s*\(\s*(?P<inner>.+?)\s*,\s*(?P<precision>\d+)\s*\)$", expr, re.IGNORECASE | re.DOTALL)
        if round_m:
            inner_translation = _translate_core(round_m.group("inner").strip(), table_name)
            translation = DaxTranslation(
                expression=f"ROUND({inner_translation.expression}, {round_m.group('precision')})",
                aggregation="ROUND",
                source_column=inner_translation.source_column,
                is_currency=inner_translation.is_currency,
                is_percentage=inner_translation.is_percentage,
            )
        else:
            translation = _translate_core(expr, table_name)

        translations.append(_apply_where_filter(translation, condition, table_name))

    if not translations:
        raise SQLToDaxError(
            f"Cannot translate SQL to basic DAX (no aggregate calls found): {sql_query!r}"
        )
    return translations


def extract_group_by_column(sql_query: str) -> str | None:
    """
    For chart-type KPIs (barChart/lineChart/table), the KPI's SQL typically
    GROUPs BY a category/date column -- that's the column the visual's
    Category/Rows role binds to. Returns the bare column name being grouped
    on, or None if there's no GROUP BY (e.g. a plain card-style aggregate).

    Handles three shapes:
      - GROUP BY <Column>                        -> "Column"
      - GROUP BY strftime('<fmt>', <Column>)      -> "Column" (innermost arg,
        not the function name -- this is the date-truncation pattern the
        Domain/KPI node uses for "Monthly X Trend" style KPIs)
      - GROUP BY <Column1>, <Column2>, ...        -> "Column1" (the FIRST
        column only -- e.g. online_retail's "Top 10 Products by Quantity
        Sold": GROUP BY StockCode, Description. A table visual's category/
        Rows role binds to one primary grouping column; Description here is
        a co-grouped display column, not a second independent category, so
        taking just the first is the correct single binding rather than an
        arbitrary choice.)
    """
    sql_query = _normalize_identifiers(sql_query)  # bug fix 7.1a
    match = re.search(
        r"GROUP\s+BY\s+(?P<expr>.+?)(?:\s+ORDER\s+BY|\s+LIMIT|\s*$)",
        sql_query,
        re.IGNORECASE | re.DOTALL,
    )
    if not match:
        return None
    expr = match.group("expr").strip()

    # Multi-column GROUP BY (comma-separated, no nested function calls in
    # this shape) -- take the first column only. Checked before the
    # single-function-call case below since a plain "A, B" has no
    # wrapping parens to match that pattern anyway, but explicit ordering
    # avoids any ambiguity.
    if "," in expr and "(" not in expr:
        first = expr.split(",")[0].strip()
        plain_first_match = re.match(r"^([A-Za-z_][A-Za-z0-9_]*)$", first)
        if plain_first_match:
            return plain_first_match.group(1)

    func_call = re.match(r"^\w+\s*\((?P<args>.+)\)\s*$", expr)
    if func_call:
        args = func_call.group("args")
        idents = re.findall(r"[A-Za-z_][A-Za-z0-9_]*", args)
        return idents[-1] if idents else None

    plain_match = re.match(r"^([A-Za-z_][A-Za-z0-9_]*)$", expr)
    if plain_match:
        bare_name = plain_match.group(1)
        # BUG FIX (2026-07-12): a bare GROUP BY identifier is not
        # guaranteed to be a real column -- SQLite (and standard SQL)
        # allows GROUP BY to reference a SELECT-list ALIAS instead of
        # repeating its expression, e.g. online_retail's "Monthly Sales
        # Trend": SELECT strftime('%Y-%m', InvoiceDate) AS sales_month, ...
        # GROUP BY sales_month. Returning "sales_month" directly here would
        # produce a visual.json Category binding to a column that doesn't
        # exist in the table (only InvoiceDate does) -- the DAX measure
        # would still compile, but the chart's category axis would be
        # broken when opened in Power BI Desktop. Chinook's equivalent KPI
        # doesn't hit this (it repeats the full strftime(...) expression in
        # its own GROUP BY rather than using the alias), which is why this
        # went unnoticed until a real dataset that uses the alias form was
        # tested. Resolve: if bare_name matches a SELECT-list alias whose
        # own expression is itself a function call over a real column
        # (e.g. "strftime('%Y-%m', InvoiceDate) AS sales_month"), return
        # that inner column instead of the alias.
        resolved = _resolve_group_by_alias(sql_query, bare_name)
        return resolved if resolved is not None else bare_name

    return None


def _resolve_group_by_alias(sql_query: str, alias: str) -> str | None:
    """
    Looks for "<expr> AS <alias>" in the SELECT list, where <expr> is
    itself a function call (e.g. strftime('%Y-%m', InvoiceDate)) -- if
    found, returns the innermost real column name inside that function
    call. Returns None if no such alias/expression pair is found (the
    bare GROUP BY identifier was already a real column, or the alias's own
    expression isn't a recognized function-call shape).
    """
    select_match = re.match(r"^SELECT\s+(?P<cols>.+?)\s+FROM\s", sql_query.strip(), re.IGNORECASE | re.DOTALL)
    if not select_match:
        return None

    for item in _split_top_level_commas(select_match.group("cols")):
        item = item.strip()
        m = re.match(rf"^(?P<expr>.+?)\s+AS\s+{re.escape(alias)}\s*$", item, re.IGNORECASE | re.DOTALL)
        if not m:
            continue
        inner_expr = m.group("expr").strip()
        func_call = re.match(r"^\w+\s*\((?P<args>.+)\)\s*$", inner_expr)
        if func_call:
            idents = re.findall(r"[A-Za-z_][A-Za-z0-9_]*", func_call.group("args"))
            return idents[-1] if idents else None
    return None
